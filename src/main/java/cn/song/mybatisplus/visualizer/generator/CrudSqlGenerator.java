package cn.song.mybatisplus.visualizer.generator;

import cn.song.mybatisplus.visualizer.model.BatchColumn;
import cn.song.mybatisplus.visualizer.model.BatchKind;
import cn.song.mybatisplus.visualizer.model.BatchModel;
import cn.song.mybatisplus.visualizer.model.PreviewResult;
import cn.song.mybatisplus.visualizer.sql.ParamHint;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.jetbrains.annotations.Nullable;

/**
 * CRUD SQL 生成器（T-CrudSql-01）。
 *
 * <p>输入 {@link CrudTableSpec}（实体类与数据库表两个入口各自适配），输出候选语句列表。
 * 纯 Java、无 PSI/IDE 依赖，测试沙盒直接单测。渲染分工：
 * <ul>
 *  <li>INSERT/UPDATE：<b>复用 {@link BatchModel#renderSql}（唯一渲染源）</b>——列级勾选、自增主键默认不勾、
 *      UPDATE 主键进 fixedColumns、方言保留字包裹、@Version 追加 {@code version = version + 1}、勾回自增列
 *      时的 identity 包装（O-52）全部继承；</li>
 *  <li>SELECT/DELETE（及无主键降级形态）：本类文本拼接，保留字引用走同一 dialect。</li>
 * </ul>
 *
 * <p>无主键降级定案（计划 §3.1）：WHERE 生成 {@code 1 = 0 /* 未识别到主键 *}{@code /}，不猜测首列；
 * 降级 UPDATE 不挂 batchModel（勾选重建会重放出无 WHERE 的破坏性 UPDATE）。</p>
 *
 * <p>双轨别名约定（T-DmlAliasGuard，O-27）：<b>别名只允许出现在查询源位（FROM/JOIN），DML
 * 目标位（INSERT INTO / UPDATE / DELETE FROM 后紧跟的表名）禁别名</b>（INSERT 目标不收
 * 别名，UPDATE/DELETE 目标别名是部分方言语法错——DBX 9bf52da 同款语义位约束）。本链
 * 现状零别名；未来任何重构引入别名逻辑先撞 {@code DmlAliasGuardTest} 红灯。</p>
 */
public final class CrudSqlGenerator {

    /** Kotlin object 单例等价。 */
    public static final CrudSqlGenerator INSTANCE = new CrudSqlGenerator();

    private CrudSqlGenerator() {
    }

    /** 无主键降级 WHERE（行内注释随语句进面板，用户一眼可见原因）。 */
    private static final String NO_PK_WHERE = "1 = 0 /* 未识别到主键，请补充条件 */";

    /**
     * 生成全部候选语句（顺序：SELECT 全表 → SELECT 按主键 → INSERT → UPDATE → DELETE → 逻辑删除变体）。
     *
     * <p>无任何列时返回空列表——调用方不弹选择框。
     */
    public static List<CrudStatement> generate(CrudTableSpec spec) {
        if (spec.getColumns().isEmpty()) {
            return List.of();
        }
        List<CrudStatement> statements = new ArrayList<>();
        statements.add(selectAll(spec));
        statements.add(selectByPk(spec));
        statements.add(insert(spec));
        statements.add(update(spec));
        statements.add(delete(spec));
        if (spec.getLogicDeleteColumn() != null) {
            statements.add(logicDelete(spec, spec.getLogicDeleteColumn()));
        }
        return statements;
    }

    // ------------------------------------------------------------------
    // SELECT
    // ------------------------------------------------------------------

    private static CrudStatement selectAll(CrudTableSpec spec) {
        String sql = "SELECT " + columnList(spec) + "\nFROM " + quoted(spec, spec.getTableName());
        return new CrudStatement(CrudKind.SELECT_ALL, plainResult(spec, sql, List.of()));
    }

    private static CrudStatement selectByPk(CrudTableSpec spec) {
        List<CrudColumn> pk = spec.getPrimaryKeys();
        boolean missing = pk.isEmpty();
        String sql = "SELECT " + columnList(spec) + "\nFROM " + quoted(spec, spec.getTableName())
                + "\nWHERE " + pkWhere(spec, pk);
        return new CrudStatement(CrudKind.SELECT_BY_PK, plainResult(spec, sql, pk), missing);
    }

    // ------------------------------------------------------------------
    // INSERT / UPDATE（BatchModel 复用）
    // ------------------------------------------------------------------

    private static CrudStatement insert(CrudTableSpec spec) {
        List<BatchColumn> toggleColumns = new ArrayList<>();
        for (CrudColumn column : spec.getColumns()) {
            // 自增/数据库生成主键默认不勾（对齐 MP：IdType.AUTO 不进 INSERT 列清单）
            toggleColumns.add(toBatchColumn(column, !column.isAutoGenerated()));
        }
        BatchModel model = new BatchModel(
                BatchKind.INSERT,
                spec.getTableName(),
                toggleColumns,
                List.of(),
                null,
                null,
                spec.getDialect(),
                spec.getIdentifierCaseSource());
        return new CrudStatement(CrudKind.INSERT, batchResult(spec, model));
    }

    private static CrudStatement update(CrudTableSpec spec) {
        List<CrudColumn> pk = spec.getPrimaryKeys();
        if (pk.isEmpty()) {
            // 无主键降级：不挂 batchModel（勾选重建会重放出无 WHERE 的破坏性 UPDATE）
            List<String> sets = new ArrayList<>();
            for (CrudColumn column : spec.getColumns()) {
                sets.add(quoted(spec, column.getColumnName()) + " = ?");
            }
            String sql = "UPDATE " + quoted(spec, spec.getTableName()) + "\nSET "
                    + String.join(", ", sets) + "\nWHERE " + NO_PK_WHERE;
            return new CrudStatement(CrudKind.UPDATE, plainResult(spec, sql, spec.getColumns()), true);
        }
        String version = spec.getVersionColumn();
        // SET 列：非主键、非版本列（版本列由 versionColumn 渲染 `= version + 1` 取代）
        List<BatchColumn> toggleColumns = new ArrayList<>();
        for (CrudColumn column : spec.getColumns()) {
            if (!column.isPrimaryKey() && !column.getColumnName().equals(version)) {
                toggleColumns.add(toBatchColumn(column, true));
            }
        }
        List<BatchColumn> fixedColumns = new ArrayList<>();
        for (CrudColumn column : pk) {
            fixedColumns.add(toBatchColumn(column, true));
        }
        for (CrudColumn column : spec.getColumns()) {
            if (column.getColumnName().equals(version)) {
                fixedColumns.add(toBatchColumn(column, true));
            }
        }
        BatchModel model = new BatchModel(
                BatchKind.UPDATE,
                spec.getTableName(),
                toggleColumns,
                fixedColumns,
                version,
                null,
                spec.getDialect(),
                spec.getIdentifierCaseSource());
        return new CrudStatement(CrudKind.UPDATE, batchResult(spec, model));
    }

    // ------------------------------------------------------------------
    // DELETE / 逻辑删除变体
    // ------------------------------------------------------------------

    private static CrudStatement delete(CrudTableSpec spec) {
        List<CrudColumn> pk = spec.getPrimaryKeys();
        boolean missing = pk.isEmpty();
        String sql = "DELETE FROM " + quoted(spec, spec.getTableName()) + "\nWHERE " + pkWhere(spec, pk);
        return new CrudStatement(CrudKind.DELETE, plainResult(spec, sql, pk), missing);
    }

    /**
     * 逻辑删除变体：{@code UPDATE t SET deleted = 1 WHERE pk = ?}。
     * 删除标记值固化为字面量 1（MP {@code logic-delete-value} 默认；@TableLogic(delval=...) 非 1 的
     * 自定义形态属文档化边界，面板可直接编辑 SQL）。仅实体侧提供（DB 侧无逻辑删除元数据）。
     */
    private static CrudStatement logicDelete(CrudTableSpec spec, String logicColumn) {
        List<CrudColumn> pk = spec.getPrimaryKeys();
        boolean missing = pk.isEmpty();
        String sql = "UPDATE " + quoted(spec, spec.getTableName()) + "\nSET "
                + quoted(spec, logicColumn) + " = 1\nWHERE " + pkWhere(spec, pk);
        return new CrudStatement(CrudKind.LOGIC_DELETE, plainResult(spec, sql, pk), missing);
    }

    // ------------------------------------------------------------------
    // 拼装辅助（保留字引用与 BatchModel 同一 dialect）
    // ------------------------------------------------------------------

    private static String quoted(CrudTableSpec spec, String identifier) {
        return spec.getDialect().quoteIfNeeded(identifier, spec.getIdentifierCaseSource());
    }

    private static String columnList(CrudTableSpec spec) {
        List<String> names = new ArrayList<>();
        for (CrudColumn column : spec.getColumns()) {
            names.add(quoted(spec, column.getColumnName()));
        }
        return String.join(", ", names);
    }

    /** WHERE 子句：主键等值 AND 连接；无主键降级 {@code 1 = 0} + 行内注释。 */
    private static String pkWhere(CrudTableSpec spec, List<CrudColumn> pk) {
        if (pk.isEmpty()) {
            return NO_PK_WHERE;
        }
        List<String> parts = new ArrayList<>();
        for (CrudColumn column : pk) {
            parts.add(quoted(spec, column.getColumnName()) + " = ?");
        }
        return String.join(" AND ", parts);
    }

    // ------------------------------------------------------------------
    // PreviewResult 组装（面板契约与 SqlPreviewService 批量路径一致）
    // ------------------------------------------------------------------

    /** 普通形态（无列勾选）：{@code ?} 占位 → unresolvedParams → 面板参数行（回填提示按列类型）。 */
    private static PreviewResult plainResult(CrudTableSpec spec, String sql, List<CrudColumn> params) {
        List<String> unresolvedParams = new ArrayList<>();
        List<ParamHint> paramHints = new ArrayList<>();
        for (CrudColumn param : params) {
            unresolvedParams.add(param.getColumnName());
            // T-DateLiteralBackfill：日期族列提示随 plain 形态透传（ParamHint(quote=, temporal=)）
            paramHints.add(new ParamHint(param.getQuoteHint(), null, false, param.isTemporal()));
        }
        List<String> columns = new ArrayList<>();
        for (CrudColumn column : spec.getColumns()) {
            columns.add(column.getColumnName());
        }
        return new PreviewResult(
                sql,
                sql,
                unresolvedParams,
                null,
                null,
                spec.getTableName(),
                null,
                columns,
                commentMap(spec),
                null,
                null,
                paramHints,
                List.of(),
                null,
                null,
                Map.of(),
                null,
                null,
                null,
                null,
                Map.of(),
                null,
                false,
                null,
                null,
                List.of(),
                Set.of(),
                null,
                null,
                null,
                spec.getDialect(),
                null,
                "",
                null);
    }

    /** 批量形态（INSERT/UPDATE）：初始 SQL 与参数登记出自 {@link BatchModel}（唯一渲染源）。 */
    private static PreviewResult batchResult(CrudTableSpec spec, BatchModel model) {
        Set<String> initialActive = new LinkedHashSet<>();
        for (BatchColumn column : model.getToggleColumns()) {
            if (column.isChecked()) {
                initialActive.add(column.getColumnName());
            }
        }
        List<String> columns = new ArrayList<>();
        for (CrudColumn column : spec.getColumns()) {
            columns.add(column.getColumnName());
        }
        return new PreviewResult(
                model.renderSql(initialActive),
                model.renderSql(initialActive),
                model.orderedSources(initialActive),
                null,
                null,
                spec.getTableName(),
                null,
                columns,
                commentMap(spec),
                null,
                null,
                model.orderedHints(initialActive),
                List.of(),
                model,
                null,
                Map.of(),
                null,
                null,
                null,
                null,
                Map.of(),
                null,
                false,
                null,
                null,
                List.of(),
                Set.of(),
                null,
                null,
                null,
                spec.getDialect(),
                null,
                "",
                null);
    }

    private static Map<String, String> commentMap(CrudTableSpec spec) {
        Map<String, String> result = new LinkedHashMap<>();
        for (CrudColumn column : spec.getColumns()) {
            if (column.getComment() != null) {
                result.put(column.getColumnName(), column.getComment());
            }
        }
        return result;
    }

    /**
     * CrudColumn → BatchColumn（参数来源统一用列名，实体/数据库两侧一致）。
     *
     * <p>O-52：{@code autoGenerated} 一并接线——{@link BatchModel#renderSql} 的 INSERT 分支据此判定是否过
     * {@code Dialect.renderInsertWrapper}（默认不勾自增列 → 不触发）。
     */
    private static BatchColumn toBatchColumn(CrudColumn column, boolean checked) {
        return new BatchColumn(column.getColumnName(), column.getColumnName(), column.getQuoteHint(), checked,
                column.isAutoGenerated(), column.getFill(), column.isTemporal());
    }
}
