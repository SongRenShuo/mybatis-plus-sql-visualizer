package cn.song.mybatisplus.visualizer.generator;

import java.util.Objects;
import org.jetbrains.annotations.Nullable;

/**
 * CRUD 生成列（T-CrudSql-01）：统一表描述的最小列单元。
 *
 * <p>两个入口各自适配进本模型——实体侧来自 {@link cn.song.mybatisplus.visualizer.psi.EntityResolver}
 * 的 {@link cn.song.mybatisplus.visualizer.model.ColumnInfo}，数据库侧来自 DbTable/DasTable 自省元数据
 * （{@link cn.song.mybatisplus.visualizer.database.DbTableSpecAdapter}）。核心生成器只认本模型，
 * 不依赖 PSI / database 插件类，测试沙盒（无 database 插件）可直接单测。
 *
 * @param columnName    数据库列名
 * @param comment       列注释（实体侧注解/文档注释；DB 侧自省 comment），面板补全提示用
 * @param isPrimaryKey  主键列
 * @param autoGenerated 自增/数据库生成（实体侧 @TableId(type=IdType.AUTO)；DB 侧 AUTO_GENERATED 属性）——
 *                      INSERT 模板默认不勾选（对齐 MP：自增主键不进 INSERT 列清单）
 * @param quoteHint     参数回填引号提示（true=加引号/false=数值原样/null=面板启发式兜底）
 * @param fill          MP 自动填充模式（@TableField(fill=FieldFill.X)，实体侧解析值如
 *                      INSERT/UPDATE/INSERT_UPDATE；R48——仿真角标与手填模拟值的数据面。
 *                      DB 侧自省无此元数据恒 null）
 * @param temporal      T-DateLiteralBackfill：日期/时间列——参数行产出 ANSI 类型字面量。
 */
public final class CrudColumn {
    private final String columnName;
    private final String comment;
    private final boolean isPrimaryKey;
    private final boolean autoGenerated;
    private final Boolean quoteHint;
    private final String fill;
    private final boolean temporal;

    public CrudColumn(String columnName, @Nullable String comment, boolean isPrimaryKey,
                      boolean autoGenerated, @Nullable Boolean quoteHint, @Nullable String fill,
                      boolean temporal) {
        this.columnName = columnName;
        this.comment = comment;
        this.isPrimaryKey = isPrimaryKey;
        this.autoGenerated = autoGenerated;
        this.quoteHint = quoteHint;
        this.fill = fill;
        this.temporal = temporal;
    }

    public CrudColumn(String columnName, @Nullable String comment, boolean isPrimaryKey,
                      boolean autoGenerated, @Nullable Boolean quoteHint, @Nullable String fill) {
        this(columnName, comment, isPrimaryKey, autoGenerated, quoteHint, fill, false);
    }

    /** Kotlin 位置实参形态（{@code fill} 取默认 null，尾参 {@code temporal} 直传）——DB 侧自省入口。 */
    public CrudColumn(String columnName, @Nullable String comment, boolean isPrimaryKey,
                      boolean autoGenerated, @Nullable Boolean quoteHint, boolean temporal) {
        this(columnName, comment, isPrimaryKey, autoGenerated, quoteHint, null, temporal);
    }

    public CrudColumn(String columnName, @Nullable String comment, boolean isPrimaryKey,
                      boolean autoGenerated, @Nullable Boolean quoteHint) {
        this(columnName, comment, isPrimaryKey, autoGenerated, quoteHint, null, false);
    }

    public CrudColumn(String columnName, @Nullable String comment, boolean isPrimaryKey, boolean autoGenerated) {
        this(columnName, comment, isPrimaryKey, autoGenerated, null);
    }

    public CrudColumn(String columnName, @Nullable String comment, boolean isPrimaryKey) {
        this(columnName, comment, isPrimaryKey, false, null);
    }

    public CrudColumn(String columnName, @Nullable String comment) {
        this(columnName, comment, false, false, null);
    }

    public CrudColumn(String columnName) {
        this(columnName, null, false, false, null);
    }

    public String getColumnName() {
        return columnName;
    }

    @Nullable
    public String getComment() {
        return comment;
    }

    public boolean isPrimaryKey() {
        return isPrimaryKey;
    }

    /** 兼容 Kotlin data class 装箱 Boolean 属性的 getter 命名（getComment 见上；此处对齐 is 前缀双路）。 */
    public boolean getIsPrimaryKey() {
        return isPrimaryKey;
    }

    public boolean isAutoGenerated() {
        return autoGenerated;
    }

    public boolean getAutoGenerated() {
        return autoGenerated;
    }

    @Nullable
    public Boolean getQuoteHint() {
        return quoteHint;
    }

    @Nullable
    public String getFill() {
        return fill;
    }

    public boolean isTemporal() {
        return temporal;
    }

    public boolean getTemporal() {
        return temporal;
    }

    public CrudColumn copy(String columnName, @Nullable String comment, boolean isPrimaryKey,
                           boolean autoGenerated, @Nullable Boolean quoteHint, @Nullable String fill,
                           boolean temporal) {
        return new CrudColumn(columnName, comment, isPrimaryKey, autoGenerated, quoteHint, fill, temporal);
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof CrudColumn)) {
            return false;
        }
        CrudColumn that = (CrudColumn) o;
        return isPrimaryKey == that.isPrimaryKey
                && autoGenerated == that.autoGenerated
                && temporal == that.temporal
                && Objects.equals(columnName, that.columnName)
                && Objects.equals(comment, that.comment)
                && Objects.equals(quoteHint, that.quoteHint)
                && Objects.equals(fill, that.fill);
    }

    @Override
    public int hashCode() {
        return Objects.hash(columnName, comment, isPrimaryKey, autoGenerated, quoteHint, fill, temporal);
    }

    @Override
    public String toString() {
        return "CrudColumn(columnName=" + columnName + ", comment=" + comment + ", isPrimaryKey=" + isPrimaryKey
                + ", autoGenerated=" + autoGenerated + ", quoteHint=" + quoteHint + ", fill=" + fill
                + ", temporal=" + temporal + ")";
    }
}
