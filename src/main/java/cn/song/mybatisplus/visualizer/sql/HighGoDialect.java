package cn.song.mybatisplus.visualizer.sql;

import cn.song.mybatisplus.visualizer.model.LimitClause;

import java.util.List;
import java.util.Set;

/**
 * 瀚高（HighGo DB）方言（T-XcDialects3 券 01）：第 13 个方言。PG 族形态
 * （{@code LIMIT {count} OFFSET {offset}} / 双引号 / {@link IdentifierFolding#LOWER} / PG 形态 upsert），
 * 独立 object 的理由同 {@link GaussDbDialect}——形态可复用、身份与保留字必须分叉
 * （{@link SqlKeywords#HIGHGO_RESERVED} 与 {@code PG_RESERVED} 双向差集 65+1 词）。
 *
 * <h2>证据级别</h2>
 *
 * <p><b>社区镜像引擎级实证</b>（HighGo V6.0.1 / PostgreSQL 12.3 内核，镜像 {@code xuxuclassmate/highgo:6.0.1}，
 * <b>非厂商官方发布物</b>，2026-10-30 探针）。厂商官方容器不存在（Docker Hub 无官方组织账号），
 * 社区镜像与官方 tar 同源但未经厂商渠道分发，故不写「厂商引擎级」。</p>
 *
 * <h2>逐项依据（除保留字外均有引擎实测背书）</h2>
 * <ul>
 *  <li>事务 {@code BEGIN}：实测 {@code BEGIN} → {@code SELECT} → {@code COMMIT} 逐条通过；</li>
 *  <li>分页 PG 形态：实测 {@code LIMIT 1, 2} 报 {@code LIMIT #,# syntax is not supported}——逗号形态不可用，
 *      只渲染 {@code LIMIT {count} OFFSET {offset}}；</li>
 *  <li>折叠 LOWER：实测裸大写 {@code INFORMATION_SCHEMA.TABLES} 折小写命中、
 *      {@code information_schema."TABLES"} 报 relation 不存在（引号保留大小写 → 大写名不存在）；</li>
 *  <li>upsert PG 形态 {@code ON CONFLICT (k) DO UPDATE SET c = EXCLUDED.c}：实测 {@code EXPLAIN INSERT …
 *      ON CONFLICT} 计划含 {@code Conflict Resolution: UPDATE} + arbiter index（冲突插入语义生效）；
 *      对照 {@code ON DUPLICATE KEY UPDATE} 实测语法错误；</li>
 *  <li>DELETE 的 {@code LIMIT} 尾段：实测 {@code DELETE … LIMIT} 报 {@code syntax error at or near "LIMIT"}
 *      （与官方 DELETE 文法无 LIMIT 尾段互证）；</li>
 *  <li>identity：{@code GENERATED BY DEFAULT} 接受显式值、{@code GENERATED ALWAYS} 需语句内
 *      {@code OVERRIDING SYSTEM VALUE}（不是前置语句包装）→ {@code renderInsertWrapper} 保持默认 null。</li>
 * </ul>
 *
 * <h2>兼容模式边界</h2>
 *
 * <p>V9 实例默认 Oracle 兼容模式（{@code initdb --dbmode} 默认 {@code oracle}，IvorySQL 血统）；Oracle 模式的
 * {@code identifier_case_switch = INTERCHANGE} 对<b>带引号</b>标识符大小写互换——逐形态推演结论是
 * LOWER 族引用规则不会因此更差（唯一不可命中形态是「以引号创建的全大写名」，见调研报告 §5.5），
 * 不做模式分叉（模式感知登记为观察项，D2 定案本轮不做）。</p>
 */
public final class HighGoDialect implements Dialect {

    public static final HighGoDialect INSTANCE = new HighGoDialect();

    private HighGoDialect() {}

    @Override
    public String getName() {
        return "HighGo";
    }

    /**
     * R36：{@code BEGIN}（社区镜像引擎级实证：BEGIN/SELECT/COMMIT 通过；官方 {@code START TRANSACTION}
     * 原文「与 BEGIN 功能相同」同向）。
     */
    @Override
    public String getTransactionBegin() {
        return "BEGIN";
    }

    @Override
    public String renderLimit(LimitClause limit) {
        return Dialect.renderPgStyleLimit(limit);
    }

    @Override
    public String quoteIdentifier(String identifier) {
        return "\"" + identifier + "\"";
    }

    @Override
    public Set<Character> getIdentifierQuotes() {
        return Set.of('"');
    }

    /** 裸标识符折小写（社区镜像引擎级实证，与 PG/KingBase/openGauss/GaussDB 同族）。 */
    @Override
    public IdentifierFolding getIdentifierFolding() {
        return IdentifierFolding.LOWER;
    }

    /**
     * 实测 {@code DELETE … LIMIT} 报 {@code syntax error at or near "LIMIT"}（引擎级，非遗漏）；
     * 官方 DELETE 文法完整大纲同样无 {@code LIMIT} 尾段，两档互证。
     */
    @Override
    public boolean getSupportsDeleteLimit() {
        return false;
    }

    @Override
    public Set<String> getReservedWords() {
        return SqlKeywords.HIGHGO_RESERVED;
    }

    /**
     * PG 形态 upsert（社区镜像引擎级实证：EXPLAIN 计划含 {@code Conflict Resolution: UPDATE} +
     * arbiter index；{@code ON DUPLICATE KEY UPDATE} 同实例实测语法错误——与 openGauss 相反，照抄
     * 同为 PG 系的 openGauss 会产出语法错误 SQL）。
     */
    @Override
    public String renderUpsert(String conflictKey, List<String> updateColumns,
                               IdentifierCaseSource caseSource) {
        return Dialect.renderPgStyleUpsert(this, conflictKey, updateColumns, caseSource);
    }
}
