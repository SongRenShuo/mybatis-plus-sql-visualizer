package cn.song.mybatisplus.visualizer.generator

import cn.song.mybatisplus.visualizer.model.BatchColumn
import cn.song.mybatisplus.visualizer.model.BatchKind
import cn.song.mybatisplus.visualizer.model.BatchModel
import cn.song.mybatisplus.visualizer.model.PreviewResult
import cn.song.mybatisplus.visualizer.sql.ParamHint

/**
 * CRUD SQL 生成器（T-CrudSql-01）。
 *
 * 输入 [CrudTableSpec]（实体类与数据库表两个入口各自适配），输出候选语句列表。
 * 纯 Kotlin、无 PSI/IDE 依赖，测试沙盒直接单测。渲染分工：
 *  - INSERT/UPDATE：**复用 [BatchModel.renderSql]（唯一渲染源）**——列级勾选、自增主键默认不勾、
 *    UPDATE 主键进 fixedColumns、方言保留字包裹、@Version 追加 `version = version + 1`、勾回自增列
 *    时的 identity 包装（O-52）全部继承；
 *  - SELECT/DELETE（及无主键降级形态）：本类文本拼接，保留字引用走同一 dialect。
 *
 * 无主键降级定案（计划 §3.1）：WHERE 生成 `1 = 0 /* 未识别到主键 */`，不猜测首列；
 * 降级 UPDATE 不挂 batchModel（勾选重建会重放出无 WHERE 的破坏性 UPDATE）。
 *
 * 双轨别名约定（T-DmlAliasGuard，O-27）：**别名只允许出现在查询源位（FROM/JOIN），DML
 * 目标位（INSERT INTO / UPDATE / DELETE FROM 后紧跟的表名）禁别名**（INSERT 目标不收
 * 别名，UPDATE/DELETE 目标别名是部分方言语法错——DBX 9bf52da 同款语义位约束）。本链
 * 现状零别名；未来任何重构引入别名逻辑先撞 `DmlAliasGuardTest` 红灯。
 */
object CrudSqlGenerator {

    /** 无主键降级 WHERE（行内注释随语句进面板，用户一眼可见原因）。 */
    private const val NO_PK_WHERE = "1 = 0 /* 未识别到主键，请补充条件 */"

    /**
     * 生成全部候选语句（顺序：SELECT 全表 → SELECT 按主键 → INSERT → UPDATE → DELETE → 逻辑删除变体）。
     *
     * 无任何列时返回 emptyList——调用方不弹选择框。
     */
    fun generate(spec: CrudTableSpec): List<CrudStatement> {
        if (spec.columns.isEmpty()) return emptyList()
        val statements = mutableListOf<CrudStatement>()
        statements += selectAll(spec)
        statements += selectByPk(spec)
        statements += insert(spec)
        statements += update(spec)
        statements += delete(spec)
        spec.logicDeleteColumn?.let { statements += logicDelete(spec, it) }
        return statements
    }

    // ------------------------------------------------------------------
    // SELECT
    // ------------------------------------------------------------------

    private fun selectAll(spec: CrudTableSpec): CrudStatement {
        val sql = "SELECT ${columnList(spec)}\nFROM ${quoted(spec, spec.tableName)}"
        return CrudStatement(CrudKind.SELECT_ALL, plainResult(spec, sql, params = emptyList()))
    }

    private fun selectByPk(spec: CrudTableSpec): CrudStatement {
        val pk = spec.primaryKeys
        val missing = pk.isEmpty()
        val sql = "SELECT ${columnList(spec)}\nFROM ${quoted(spec, spec.tableName)}\nWHERE ${pkWhere(spec, pk)}"
        return CrudStatement(
            CrudKind.SELECT_BY_PK,
            plainResult(spec, sql, params = pk),
            missingPrimaryKey = missing,
        )
    }

    // ------------------------------------------------------------------
    // INSERT / UPDATE（BatchModel 复用）
    // ------------------------------------------------------------------

    private fun insert(spec: CrudTableSpec): CrudStatement {
        val model = BatchModel(
            kind = BatchKind.INSERT,
            tableName = spec.tableName,
            // 自增/数据库生成主键默认不勾（对齐 MP：IdType.AUTO 不进 INSERT 列清单）
            toggleColumns = spec.columns.map { it.toBatchColumn(checked = !it.autoGenerated) },
            dialect = spec.dialect,
            identifierCaseSource = spec.identifierCaseSource,
        )
        return CrudStatement(CrudKind.INSERT, batchResult(spec, model))
    }

    private fun update(spec: CrudTableSpec): CrudStatement {
        val pk = spec.primaryKeys
        if (pk.isEmpty()) {
            // 无主键降级：不挂 batchModel（勾选重建会重放出无 WHERE 的破坏性 UPDATE）
            val setSql = spec.columns.joinToString(", ") { "${quoted(spec, it.columnName)} = ?" }
            val sql = "UPDATE ${quoted(spec, spec.tableName)}\nSET $setSql\nWHERE $NO_PK_WHERE"
            return CrudStatement(
                CrudKind.UPDATE,
                plainResult(spec, sql, params = spec.columns),
                missingPrimaryKey = true,
            )
        }
        val version = spec.versionColumn
        val model = BatchModel(
            kind = BatchKind.UPDATE,
            tableName = spec.tableName,
            // SET 列：非主键、非版本列（版本列由 versionColumn 渲染 `= version + 1` 取代）
            toggleColumns = spec.columns
                .filter { !it.isPrimaryKey && it.columnName != version }
                .map { it.toBatchColumn(checked = true) },
            fixedColumns = (pk + spec.columns.filter { it.columnName == version })
                .map { it.toBatchColumn(checked = true) },
            versionColumn = version,
            dialect = spec.dialect,
            identifierCaseSource = spec.identifierCaseSource,
        )
        return CrudStatement(CrudKind.UPDATE, batchResult(spec, model))
    }

    // ------------------------------------------------------------------
    // DELETE / 逻辑删除变体
    // ------------------------------------------------------------------

    private fun delete(spec: CrudTableSpec): CrudStatement {
        val pk = spec.primaryKeys
        val missing = pk.isEmpty()
        val sql = "DELETE FROM ${quoted(spec, spec.tableName)}\nWHERE ${pkWhere(spec, pk)}"
        return CrudStatement(
            CrudKind.DELETE,
            plainResult(spec, sql, params = pk),
            missingPrimaryKey = missing,
        )
    }

    /**
     * 逻辑删除变体：`UPDATE t SET deleted = 1 WHERE pk = ?`。
     * 删除标记值固化为字面量 1（MP `logic-delete-value` 默认；@TableLogic(delval=...) 非 1 的
     * 自定义形态属文档化边界，面板可直接编辑 SQL）。仅实体侧提供（DB 侧无逻辑删除元数据）。
     */
    private fun logicDelete(spec: CrudTableSpec, logicColumn: String): CrudStatement {
        val pk = spec.primaryKeys
        val missing = pk.isEmpty()
        val sql = "UPDATE ${quoted(spec, spec.tableName)}\nSET ${quoted(spec, logicColumn)} = 1\nWHERE ${pkWhere(spec, pk)}"
        return CrudStatement(
            CrudKind.LOGIC_DELETE,
            plainResult(spec, sql, params = pk),
            missingPrimaryKey = missing,
        )
    }

    // ------------------------------------------------------------------
    // 拼装辅助（保留字引用与 BatchModel 同一 dialect）
    // ------------------------------------------------------------------

    private fun quoted(spec: CrudTableSpec, identifier: String): String =
        spec.dialect.quoteIfNeeded(identifier, spec.identifierCaseSource)

    private fun columnList(spec: CrudTableSpec): String = spec.columns.joinToString(", ") { quoted(spec, it.columnName) }

    /** WHERE 子句：主键等值 AND 连接；无主键降级 `1 = 0` + 行内注释。 */
    private fun pkWhere(spec: CrudTableSpec, pk: List<CrudColumn>): String =
        if (pk.isEmpty()) NO_PK_WHERE else pk.joinToString(" AND ") { "${quoted(spec, it.columnName)} = ?" }

    // ------------------------------------------------------------------
    // PreviewResult 组装（面板契约与 SqlPreviewService 批量路径一致）
    // ------------------------------------------------------------------

    /** 普通形态（无列勾选）：`?` 占位 → unresolvedParams → 面板参数行（回填提示按列类型）。 */
    private fun plainResult(spec: CrudTableSpec, sql: String, params: List<CrudColumn>): PreviewResult =
        PreviewResult(
            sql = sql,
            compactSql = sql,
            unresolvedParams = params.map { it.columnName },
            paramTable = null,
            wrapperType = null,
            tableName = spec.tableName,
            paramHints = params.map { ParamHint(quote = it.quoteHint, temporal = it.temporal) },
            columns = spec.columns.map { it.columnName },
            columnComments = commentMap(spec),
            renderedDialect = spec.dialect,
        )

    /** 批量形态（INSERT/UPDATE）：初始 SQL 与参数登记出自 [BatchModel]（唯一渲染源）。 */
    private fun batchResult(spec: CrudTableSpec, model: BatchModel): PreviewResult {
        val initialActive = model.toggleColumns.filter { it.checked }.map { it.columnName }.toSet()
        return PreviewResult(
            sql = model.renderSql(initialActive),
            compactSql = model.renderSql(initialActive),
            unresolvedParams = model.orderedSources(initialActive),
            paramTable = null,
            wrapperType = null,
            tableName = spec.tableName,
            paramHints = model.orderedHints(initialActive),
            columns = spec.columns.map { it.columnName },
            columnComments = commentMap(spec),
            batchModel = model,
            renderedDialect = spec.dialect,
        )
    }

    private fun commentMap(spec: CrudTableSpec): Map<String, String> =
        spec.columns.mapNotNull { c -> c.comment?.let { c.columnName to it } }.toMap()

    /**
     * CrudColumn → BatchColumn（参数来源统一用列名，实体/数据库两侧一致）。
     *
     * O-52：`autoGenerated` 一并接线——[BatchModel.renderSql] 的 INSERT 分支据此判定是否过
     * [cn.song.mybatisplus.visualizer.sql.Dialect.renderInsertWrapper]（默认不勾自增列 → 不触发）。
     */
    private fun CrudColumn.toBatchColumn(checked: Boolean): BatchColumn =
        BatchColumn(
            columnName = columnName,
            source = columnName,
            quote = quoteHint,
            checked = checked,
            autoGenerated = autoGenerated,
            fill = fill,
            temporal = temporal,
        )
}
