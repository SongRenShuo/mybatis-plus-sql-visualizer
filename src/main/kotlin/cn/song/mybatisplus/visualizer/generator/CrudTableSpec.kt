package cn.song.mybatisplus.visualizer.generator

import cn.song.mybatisplus.visualizer.model.PreviewResult
import cn.song.mybatisplus.visualizer.sql.Dialect
import cn.song.mybatisplus.visualizer.sql.IdentifierCaseSource
import cn.song.mybatisplus.visualizer.sql.MySqlDialect

/**
 * CRUD 生成列（T-CrudSql-01）：统一表描述的最小列单元。
 *
 * 两个入口各自适配进本模型——实体侧来自 [cn.song.mybatisplus.visualizer.psi.EntityResolver]
 * 的 [cn.song.mybatisplus.visualizer.model.ColumnInfo]，数据库侧来自 DbTable/DasTable 自省元数据
 * （[cn.song.mybatisplus.visualizer.database.DbTableSpecAdapter]）。核心生成器只认本模型，
 * 不依赖 PSI / database 插件类，测试沙盒（无 database 插件）可直接单测。
 *
 * @param columnName    数据库列名
 * @param comment       列注释（实体侧注解/文档注释；DB 侧自省 comment），面板补全提示用
 * @param isPrimaryKey  主键列
 * @param autoGenerated 自增/数据库生成（实体侧 @TableId(type=IdType.AUTO)；DB 侧 AUTO_GENERATED 属性）——
 *                      INSERT 模板默认不勾选（对齐 MP：自增主键不进 INSERT 列清单）
 * @param quoteHint     参数回填引号提示（true=加引号/false=数值原样/null=面板启发式兜底）
 * @param fill          MP 自动填充模式（@TableField(fill=FieldFill.X)，实体侧解析值如
 *                      INSERT/UPDATE/INSERT_UPDATE；R48——仿真角标与手填模拟值的数据面。
 *                      DB 侧自省无此元数据恒 null）
 */
data class CrudColumn(
    val columnName: String,
    val comment: String? = null,
    val isPrimaryKey: Boolean = false,
    val autoGenerated: Boolean = false,
    val quoteHint: Boolean? = null,
    val fill: String? = null,
    /** T-DateLiteralBackfill：日期/时间列——参数行产出 ANSI 类型字面量。 */
    val temporal: Boolean = false,
)

/**
 * 统一表描述（T-CrudSql-01）：实体类与数据库表两个入口的公共目标模型。
 *
 * @param tableName         表名
 * @param columns           列清单（顺序即渲染顺序：实体侧经角色分组稳定排序；DB 侧自省顺序）
 * @param logicDeleteColumn 逻辑删除列（实体侧 @TableLogic；DB 侧无此元数据恒 null——
 *                          物理删除之外是否提供逻辑删除变体由本列决定）
 * @param versionColumn     乐观锁版本列（实体侧 @Version，对齐 updateById 语义：SET 由
 *                          `version = version + 1` 取代、WHERE 末尾追加；DB 侧无此元数据恒 null）
 * @param dialect           方言（保留字引用包裹；读插件设置，缺省 MySQL）
 * @param identifierCaseSource 名字大小写来源（O-42；O-51 起按方言折叠方向族分流）：目录来源
 *                          [IdentifierCaseSource.CATALOG] 时按 [Dialect.identifierFolding] 引用
 *                          （UPPER 族含小写即加引号 / LOWER 族含大写即加引号 / NONE 族不判）；
 *                          缺省 [IdentifierCaseSource.ENTITY]（实体派生名裸写，既有行为逐字不变
 *                          ——未接线点也落此默认值）
 */
data class CrudTableSpec(
    val tableName: String,
    val columns: List<CrudColumn>,
    val logicDeleteColumn: String? = null,
    val versionColumn: String? = null,
    val dialect: Dialect = MySqlDialect,
    val identifierCaseSource: IdentifierCaseSource = IdentifierCaseSource.ENTITY,
) {
    /** 主键列（保持 [columns] 顺序；复合主键 AND 连接）。 */
    val primaryKeys: List<CrudColumn> get() = columns.filter { it.isPrimaryKey }

    /** 是否识别到主键——UPDATE/DELETE/按主键 SELECT 的 WHERE 子句依赖；无主键走降级形态。 */
    val hasPrimaryKey: Boolean get() = primaryKeys.isNotEmpty()
}

/**
 * CRUD 语句种类（T-CrudSql-01）：候选项标签的 bundle 键来源。
 */
enum class CrudKind(val labelKey: String) {
    SELECT_ALL("crudSql.kind.selectAll"),
    SELECT_BY_PK("crudSql.kind.selectByPk"),
    INSERT("crudSql.kind.insert"),
    UPDATE("crudSql.kind.update"),
    DELETE("crudSql.kind.delete"),
    LOGIC_DELETE("crudSql.kind.logicDelete"),
}

/**
 * 单条候选语句（T-CrudSql-01）：选择弹窗候选项的最小单元。
 *
 * @param kind              语句种类（候选标签 bundle 键）
 * @param result            组装好的预览结果（SELECT/DELETE 普通形态；INSERT/UPDATE 带 batchModel）
 * @param missingPrimaryKey 无主键降级标记（候选标签追加"未识别到主键"标注）
 */
data class CrudStatement(
    val kind: CrudKind,
    val result: PreviewResult,
    val missingPrimaryKey: Boolean = false,
)
