    /** 同 spec 双来源产物对比（[bothFoldingFamiliesChangeOutputByCaseSource] 的公共断言体）。 */
    private fun assertCaseSourceChangesOutput(
        tableName: String,
        dialect: Dialect,
        entitySql: String,
        catalogSql: String,
    ) {
        val base = CrudTableSpec(
            tableName = tableName,
            columns = listOf(CrudColumn("id", isPrimaryKey = true)),
