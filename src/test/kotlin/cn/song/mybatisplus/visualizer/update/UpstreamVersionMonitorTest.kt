package cn.song.mybatisplus.visualizer.update

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * F-11 上游 MyBatis 版本监听：纯函数判别（零平台依赖，快桶）。
 *
 * 钉住四件事：
 *  1. 两种版本来源（pom.properties / Manifest）的解析口径，含 Manifest 72 字节折行；
 *  2. 快照键的稳定形态（同集合逐字可比）；
 *  3. **无变化不打扰**（[UpstreamVersionMonitor.changed] 的核心判据）与首次探测静默；
 *  4. 探测不到时不伪造版本（空列表）。
 *
 * 平台侧（PropertiesComponent 记录 + 通知）走 [UpstreamVersionMonitor.checkOnce]，单测模式下
 * 直接返回不写记录（本类不触达），真机步骤登记计划 §实施记录。
 */
class UpstreamVersionMonitorTest {

    // ---------- pom.properties 解析 ----------

    @Test
    fun `pom解析_取version行且容忍注释与空白`() {
        val text = """
            #Generated by Maven
            #Thu Nov 06 10:00:00 CST 2026
            groupId=com.baomidou
            artifactId=mybatis-plus-core
            version=3.5.17
        """.trimIndent()
        assertEquals("3.5.17", UpstreamVersionMonitor.parsePomProperties(text))
        assertEquals("3.5.17", UpstreamVersionMonitor.parsePomProperties("  version = 3.5.17  \n"))
        assertNull("无 version 键", UpstreamVersionMonitor.parsePomProperties("artifactId=x\n"))
        assertNull("空文本", UpstreamVersionMonitor.parsePomProperties(""))
    }

    // ---------- Manifest 解析（含折行） ----------

    @Test
    fun `manifest解析_取Implementation-Version`() {
        val text = "Manifest-Version: 1.0\nImplementation-Title: mybatis\nImplementation-Version: 3.5.19\n"
        assertEquals("3.5.19", UpstreamVersionMonitor.parseManifestVersion(text))
        assertEquals("3.5.19", UpstreamVersionMonitor.parseManifestVersion("implementation-version: 3.5.19\n"))
        assertNull("无该属性", UpstreamVersionMonitor.parseManifestVersion("Manifest-Version: 1.0\n"))
    }

    @Test
    fun `manifest解析_72字节折行按规范拼接`() {
        // 规范：续行以一个空格开头，拼接时去掉该空格
        val text = "Implementation-Version: 3.5.1\n 9\n"
        assertEquals("3.5.19", UpstreamVersionMonitor.parseManifestVersion(text))
    }

    // ---------- 快照键 ----------

    @Test
    fun `快照键_按artifact排序且形态稳定`() {
        val a = UpstreamVersionMonitor.snapshotKey(
            listOf(
                UpstreamVersionMonitor.Upstream("mybatis", "3.5.19"),
                UpstreamVersionMonitor.Upstream("mybatis-plus-core", "3.5.17"),
            ),
        )
        val b = UpstreamVersionMonitor.snapshotKey(
            listOf(
                UpstreamVersionMonitor.Upstream("mybatis-plus-core", "3.5.17"),
                UpstreamVersionMonitor.Upstream("mybatis", "3.5.19"),
            ),
        )
        assertEquals("顺序无关：同集合同键", a, b)
        assertEquals("mybatis=3.5.19;mybatis-plus-core=3.5.17", a)
        assertEquals("空列表 → 空串", "", UpstreamVersionMonitor.snapshotKey(emptyList()))
    }

    // ---------- 变化判定（核心：无变化不打扰） ----------

    @Test
    fun `无变化不打扰`() {
        val key = "mybatis=3.5.19;mybatis-plus-core=3.5.17"
        assertFalse("同一快照不得提示", UpstreamVersionMonitor.changed(key, key))
    }

    @Test
    fun `首次探测静默_本次探不到也静默`() {
        assertFalse("首次（无记录）静默登记，安装首启不打扰", UpstreamVersionMonitor.changed(null, "mybatis=3.5.19"))
        assertFalse("首次且记录为空串同样静默", UpstreamVersionMonitor.changed("", "mybatis=3.5.19"))
        assertFalse("本次探不到（环境抖动）不提示", UpstreamVersionMonitor.changed("mybatis=3.5.19", null))
        assertFalse("本次空串不提示", UpstreamVersionMonitor.changed("mybatis=3.5.19", ""))
    }

    @Test
    fun `版本变化才提示`() {
        assertTrue(
            "上游升版必须提示",
            UpstreamVersionMonitor.changed("mybatis=3.5.18", "mybatis=3.5.19"),
        )
        assertTrue(
            "新增 artifact 也算变化",
            UpstreamVersionMonitor.changed("mybatis=3.5.19", "mybatis=3.5.19;mybatis-plus-core=3.5.17"),
        )
    }

    // ---------- 描述文本 ----------

    @Test
    fun `描述文本_分段换行且保留artifact名`() {
        val text = UpstreamVersionMonitor.describe("mybatis=3.5.19;mybatis-plus-core=3.5.17")
        assertTrue(text.contains("mybatis: 3.5.19"))
        assertTrue(text.contains("mybatis-plus-core: 3.5.17"))
        assertTrue("两段之间换行", text.lines().size == 2)
        assertEquals("空键 → 空文本", "", UpstreamVersionMonitor.describe(""))
    }

    // ---------- 探测边界 ----------

    @Test
    fun `探测不到返回空列表_不伪造版本`() {
        // 用一个看不见任何 mybatis 资源的类加载器（引导类加载器视野内只有 JDK）
        val empty = ClassLoader.getPlatformClassLoader()
        assertTrue(
            "探不到上游版本时必须是空列表（调用方据此保持静默）",
            UpstreamVersionMonitor.probeVersions(empty).isEmpty(),
        )
    }
}
