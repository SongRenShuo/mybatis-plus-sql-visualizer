package cn.song.mybatisplus.visualizer.sql

import cn.song.mybatisplus.visualizer.model.LimitClause
import cn.song.mybatisplus.visualizer.sql.SqlKeywords.HIGHGO_RESERVED
import cn.song.mybatisplus.visualizer.sql.SqlKeywords.KINGBASE_RESERVED
import cn.song.mybatisplus.visualizer.sql.SqlKeywords.VASTBASE_RESERVED
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertSame
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * T-XcDialects3 券 01/02/04/05：瀚高（HighGo）+ 海量（Vastbase）两方言单测与金仓 enckey 补词。
 *
 * 证据层级三态口径（2026-10-29）：
 *  - **瀚高：社区镜像引擎级实证**（HighGo V6.0.1 / PostgreSQL 12.3 内核，社区镜像
 *    `xuxuclassmate/highgo:6.0.1`——Docker Hub 无厂商官方组织账号，**非厂商官方发布物**，
 *    2026-10-30 探针）——
 *      - 事务：`BEGIN` → `SELECT` → `COMMIT` 逐条通过；
 *      - 分页：`LIMIT 1, 2` 报 `LIMIT #,# syntax is not supported`（逗号形态不可用）→ 只渲染
 *        PG 形态 `LIMIT {count} OFFSET {offset}`；
 *      - 折叠：裸大写 `INFORMATION_SCHEMA.TABLES` 折小写命中、
 *        `information_schema."TABLES"` 报 relation 不存在 → **LOWER** 实锤；
 *      - upsert：`EXPLAIN INSERT … ON CONFLICT (id) DO UPDATE SET note = EXCLUDED.note` 计划含
 *        `Conflict Resolution: UPDATE` + arbiter index（冲突插入语义生效）；对照
 *        `ON DUPLICATE KEY UPDATE` 实测语法错误 → PG 形态实锤（与 openGauss 相反）；
 *      - DELETE：`DELETE … LIMIT` 报 `syntax error at or near "LIMIT"` → 判无实锤；
 *      - identity：`GENERATED BY DEFAULT` 接受显式值、`GENERATED ALWAYS` 需语句内
 *        `OVERRIDING SYSTEM VALUE`（非前置包装）→ `renderInsertWrapper` 保持 null；
 *  - **海量：官方文档级**（docs.vastdata.com.cn G100 V3.0.9《SQL 参考》；真机部署在途，
 *    真机读数到位后升档）——upsert 取 MySQL 形态是 D3 定案（官方通用文法两种都收，默认 A 模式
 *    无真机证据，取同内核 openGauss 真机已证形态，真机证 PG 形态可用再切）；
 *  - **金仓 enckey：真机引擎级**（KingbaseES V009R001C010，2026-10-29）——
 *    `pg_get_keywords()` 标 R、列引用报 `kb: syntax error at or near "enckey"`；别名位
 *    `SELECT 1 AS enckey` 实测通过（多一对引号属可接受多包）。
 *
 * 反向验证夹具（读数见计划 §七 7.1）：`注册表身份_末两位HighGo与Vastbase_摘掉注册即红` 钉住
 * byName 命中 + 注册表末两位 + 经注册表的分页渲染——摘掉注册后 byName 回落 [MySqlDialect]、
 * 分页渲染变 MySQL 逗号形态，本用例三组断言全红。
 *
 * k2j 移植注（生产为 Java）：方言单例为 `XxxDialect.INSTANCE` 静态；保留字三集合是
 * [SqlKeywords] 的静态常量（master 顶层常量改限定导入，语义同）。
 */
class DialectXcFamily3Test {

    // ---------- 注册表身份（反向验证的绿态基准） ----------

    /**
     * 摘掉 `DialectRegistry.dialects` 末两项的反向验证中，本用例全红：byName 回落 [MySqlDialect]
     * （assertSame 失配）、末两位名单失配、经 byName 的分页渲染变 MySQL 形态
     * （`LIMIT 5, 10` ≠ `LIMIT 10 OFFSET 5`）。
     */
    @Test
    fun `注册表身份_末两位HighGo与Vastbase_摘掉注册即红`() {
        assertSame(HighGoDialect.INSTANCE, DialectRegistry.INSTANCE.byName("HighGo"))
        assertSame(VastbaseDialect.INSTANCE, DialectRegistry.INSTANCE.byName("Vastbase"))
        assertEquals(14, DialectRegistry.INSTANCE.dialects.size)
        assertEquals(listOf("HighGo", "Vastbase"), DialectRegistry.INSTANCE.dialects.takeLast(2).map { it.name })
        // 未知名/空值回退 MySQL（既有口径不被新方言稀释）
        assertSame(MySqlDialect.INSTANCE, DialectRegistry.INSTANCE.byName("NoSuchDbms"))
        assertSame(MySqlDialect.INSTANCE, DialectRegistry.INSTANCE.byName(null))
        // 经注册表的格式化链：注册在位 → PG 形态；摘掉注册 → 回落 MySQL 逗号形态即红
        assertEquals("LIMIT 10 OFFSET 5", DialectRegistry.INSTANCE.byName("HighGo").renderLimit(LimitClause(5L, 10L)))
        assertEquals("LIMIT 10 OFFSET 5", DialectRegistry.INSTANCE.byName("Vastbase").renderLimit(LimitClause(5L, 10L)))
    }

    // ---------- 折叠族与分页 ----------

    @Test
    fun `折叠族_两方言均LOWER`() {
        assertEquals(IdentifierFolding.LOWER, HighGoDialect.INSTANCE.identifierFolding)
        assertEquals(IdentifierFolding.LOWER, VastbaseDialect.INSTANCE.identifierFolding)
        // LOWER 族目录来源行为：含大写必须包（裸写被折小写 → 查不到）；全小写裸写；实体来源逐字不变
        listOf(HighGoDialect.INSTANCE, VastbaseDialect.INSTANCE).forEach { d ->
            assertEquals("方言 ${d.name} 目录来源含大写应加引号", "\"Issue_New\"", d.quoteIfNeeded("Issue_New", IdentifierCaseSource.CATALOG))
            assertEquals("方言 ${d.name} 目录来源全小写裸写", "issue_new", d.quoteIfNeeded("issue_new", IdentifierCaseSource.CATALOG))
            assertEquals("方言 ${d.name} 实体来源逐字不变", "Issue_New", d.quoteIfNeeded("Issue_New", IdentifierCaseSource.ENTITY))
        }
    }

    @Test
    fun `分页_PG形态字面量`() {
        assertEquals("LIMIT 10 OFFSET 5", HighGoDialect.INSTANCE.renderLimit(LimitClause(5L, 10L)))
        assertEquals("LIMIT 10", HighGoDialect.INSTANCE.renderLimit(LimitClause(null, 10L)))
        assertEquals("LIMIT 10 OFFSET 5", VastbaseDialect.INSTANCE.renderLimit(LimitClause(5L, 10L)))
        assertEquals("LIMIT 10", VastbaseDialect.INSTANCE.renderLimit(LimitClause(null, 10L)))
    }

    // ---------- 引号与保留字（三集合身份独立） ----------

    @Test
    fun `引号_双引号形态`() {
        assertEquals("\"id\"", HighGoDialect.INSTANCE.quoteIdentifier("id"))
        assertEquals("\"id\"", VastbaseDialect.INSTANCE.quoteIdentifier("id"))
        assertEquals(setOf('"'), HighGoDialect.INSTANCE.identifierQuotes)
        assertEquals(setOf('"'), VastbaseDialect.INSTANCE.identifierQuotes)
    }

    /**
     * 保留字抽查：三集合各有独有词，互不为超集——任一集合被改成复用他方（或退回 PG_RESERVED）
     * 即红。瀚高侧 `flashback`/`sysdate` 来自社区镜像 V6.0.1 引擎 R 类（官方 V4.5 附录 2 没有的
     * 两词）；`values` 引擎实测为非保留，按「宁可多包」仍收录。
     */
    @Test
    fun `保留字_三集合独有词抽查`() {
        // 瀚高独有抽查（flashback/sysdate 引擎补词、values 官方附录在册）
        listOf("flashback", "sysdate", "values").forEach {
            assertEquals("瀚高保留字应被引用: $it", "\"$it\"", HighGoDialect.INSTANCE.quoteIfKeyword(it))
        }
        // 海量独有抽查（A 模式比 PG 模式多的词——四模式并集的理由词）
        listOf("excluded", "online", "long").forEach {
            assertEquals("海量保留字应被引用: $it", "\"$it\"", VastbaseDialect.INSTANCE.quoteIfKeyword(it))
        }
        // 金仓 enckey（券 05：引擎标 R、官方文档标非保留，以引擎为准）
        assertTrue("\"enckey\" 应在 KINGBASE_RESERVED（真机 2026-10-29）", "enckey" in KINGBASE_RESERVED)
        assertEquals("\"enckey\"", KingBaseDialect.INSTANCE.quoteIfKeyword("enckey"))
        // 三集合身份独立：独有词不得串包
        assertFalse("excluded 不是瀚高保留字（openGauss 系才有）", "excluded" in HIGHGO_RESERVED)
        assertFalse("values 不是海量保留字（四模式表均不在册）", "values" in VASTBASE_RESERVED)
        assertFalse("enckey 不是瀚高关键字（引擎 pg_get_keywords() 无此词）", "enckey" in HIGHGO_RESERVED)
        assertFalse("enckey 不是海量关键字", "enckey" in VASTBASE_RESERVED)
        // 普通业务词不命中（防整表加引号式过包）
        assertEquals("user_name", HighGoDialect.INSTANCE.quoteIfKeyword("user_name"))
        assertEquals("user_name", VastbaseDialect.INSTANCE.quoteIfKeyword("user_name"))
    }

    // ---------- upsert / 事务 / DELETE-LIMIT / identity ----------

    @Test
    fun `upsert_两族均PG形态`() {
        // 瀚高：PG 形态（社区镜像引擎级实证——EXPLAIN 计划含 Conflict Resolution: UPDATE）
        assertEquals(
            "ON CONFLICT (id) DO UPDATE SET note = EXCLUDED.note",
            HighGoDialect.INSTANCE.renderUpsert("id", listOf("note")),
        )
        assertNull(HighGoDialect.INSTANCE.renderUpsertStatement("t", listOf("id", "note"), "id"))
        // 海量：D3 切换条款已触发——A 模式真机实证两种形态均可用，切 PG 形态（2026-10-30）
        assertEquals(
            "ON CONFLICT (id) DO UPDATE SET note = EXCLUDED.note",
            VastbaseDialect.INSTANCE.renderUpsert("id", listOf("note")),
        )
        assertNull(VastbaseDialect.INSTANCE.renderUpsertStatement("t", listOf("id", "note"), "id"))
    }

    @Test
    fun `事务_DELETE_LIMIT_identity包装`() {
        assertEquals("BEGIN", HighGoDialect.INSTANCE.transactionBegin)
        assertEquals("BEGIN", VastbaseDialect.INSTANCE.transactionBegin)
        assertFalse(HighGoDialect.INSTANCE.supportsDeleteLimit)
        // 海量：A 模式真机实证 DELETE ... LIMIT 真删生效（DELETE 1），P-7 翻 true
        assertTrue(VastbaseDialect.INSTANCE.supportsDeleteLimit)
        // identity 包装保持 null：瀚高实测 OVERRIDING SYSTEM VALUE 是语句内子句（非前置包装）；
        // 海量按官方文档同形（B 模式 AUTO_INCREMENT 允许显式写值）
        assertNull(HighGoDialect.INSTANCE.renderInsertWrapper("t", "INSERT INTO t VALUES (?)"))
        assertNull(VastbaseDialect.INSTANCE.renderInsertWrapper("t", "INSERT INTO t VALUES (?)"))
    }

    // ---------- EXPLAIN（券 04：经 ExplainSupport 表） ----------

    @Test
    fun `explain渲染_两方言JSON形态`() {
        val sample = "SELECT * FROM users WHERE id > 1"
        assertEquals("EXPLAIN (FORMAT JSON) $sample", HighGoDialect.INSTANCE.renderExplainStatement(sample))
        assertEquals("EXPLAIN (FORMAT JSON) $sample", VastbaseDialect.INSTANCE.renderExplainStatement(sample))
        assertEquals(ExplainOutputFormat.JSON, ExplainSupport.formatFor("HighGo"))
        assertEquals(ExplainOutputFormat.JSON, ExplainSupport.formatFor("Vastbase"))
        // 幂等包装（T-ExplainDbl）在新方言同样成立
        assertEquals(
            "EXPLAIN (FORMAT JSON) $sample",
            HighGoDialect.INSTANCE.renderExplainStatementIdempotent("EXPLAIN (FORMAT JSON) $sample"),
        )
    }
}
