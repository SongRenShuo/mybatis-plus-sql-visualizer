package cn.song.mybatisplus.visualizer.ui

import cn.song.mybatisplus.visualizer.execute.DataSourceSelector
import cn.song.mybatisplus.visualizer.generator.CrudColumn
import cn.song.mybatisplus.visualizer.generator.CrudKind
import cn.song.mybatisplus.visualizer.generator.CrudSqlGenerator
import cn.song.mybatisplus.visualizer.generator.CrudTableSpec
import cn.song.mybatisplus.visualizer.sql.DataSourceUrlProbe
import cn.song.mybatisplus.visualizer.testutil.PluginSettingsTestSupport
import com.intellij.openapi.command.WriteCommandAction
import com.intellij.openapi.util.Disposer
import com.intellij.testFramework.fixtures.BasePlatformTestCase
import com.intellij.util.ui.UIUtil
import org.junit.Assert.assertEquals

/**
 * S2-4 券①（承接 T-DialectInferPollution P2）：换源成功后存活预览面板按**新源方言重渲染**。
 *
 * 链路：`rememberRunner`（生产写入入口）广播 `LAST_USED_CHANGE_TOPIC` → 面板
 * `scheduleHeaderSourceRefresh` → `refreshHeaderSourceNow` → `refreshDialectStatusRow`
 * （重算决策，BOUND_DATASOURCE 强证据）→ `rerenderIfBoundDialectDiffers` → 既有渲染链
 * `rerenderForExecutionTarget`。护栏三重：仅绑定源证据 / 方言不同 / 用户未编辑文本。
 *
 * headless 取数：无 Database 插件，`boundDataSourceDialectForDecision()` 走「记忆名 → URL 探测」
 * 回落——记忆经 `plantLastUsedMemoryForTest`/`rememberedLookupForTest` 植入，URL 经
 * `probeByNameForTest` 缝注入（生产同源链，SqlPreviewPanelBindStateTest 同款口径）。
 *
 * 反向验证（20261101-1521 册 §一）：把 `refreshHeaderSourceNow` 的
 * `refreshDialectStatusRow()` 改回 `rerenderSql = false`（摘掉重渲染触发）→ 正例必红。
 */
class SourceSwitchRerenderTest : BasePlatformTestCase() {

    private var panel: SqlPreviewPanel? = null

    override fun setUp() {
        super.setUp()
        PluginSettingsTestSupport.resetToFactoryDefaults()
        runCatching { SqlPreviewPanel.resetPresetCollapsedForTest() }
        runCatching { DataSourceSelector.forgetAllLastUsed(project) }
        DataSourceUrlProbe.invalidateAllForTest()
    }

    override fun tearDown() {
        PluginSettingsTestSupport.resetToFactoryDefaults()
        DataSourceSelector.rememberedLookupForTest = null
        DataSourceUrlProbe.probeByNameForTest = null
        DataSourceUrlProbe.invalidateAllForTest()
        runCatching { DataSourceSelector.forgetAllLastUsed(project) }
        runCatching { panel?.clear() }
        panel = null
        super.tearDown()
    }

    /** 在籍数据源名单 + UUID→名解析（模拟 Database 插件注册表）。 */
    private fun plantRegisteredSources() {
        DataSourceSelector.rememberedLookupForTest = {
            listOf("mysql-src@local", "pg-src@remote", "mysql-2nd@local") to { id ->
                when (id) {
                    "uuid-mysql" -> "mysql-src@local"
                    "uuid-pg" -> "pg-src@remote"
                    "uuid-mysql2" -> "mysql-2nd@local"
                    else -> null
                }
            }
        }
    }

    /** 按源名注入 JDBC URL（生产同型读数走反射探在籍数据源，headless 不可达）。 */
    private fun plantUrlProbe() {
        DataSourceUrlProbe.probeByNameForTest = { _, name ->
            when {
                name.startsWith("pg-") -> "jdbc:postgresql://remote:5432/demo"
                else -> "jdbc:mysql://local:3306/demo"
            }
        }
    }

    /** INSERT 预览（batchModel 载体，MySQL 渲染；rerenderForExecutionTarget 可无损重渲染）。 */
    private fun openInsertPreview(): SqlPreviewPanel {
        val spec = CrudTableSpec(
            tableName = "user",
            columns = listOf(
                CrudColumn("id", isPrimaryKey = true, autoGenerated = true, quoteHint = false),
                CrudColumn("name", quoteHint = true),
            ),
        )
        val stmt = CrudSqlGenerator.generate(spec).first { it.kind == CrudKind.INSERT }
        val p = SqlPreviewPanel(project)
        panel = p
        Disposer.register(testRootDisposable, p)
        p.showResult(stmt.result)
        UIUtil.dispatchAllInvocationEvents()
        return p
    }

    /** 泵 EDT + 池线程直至条件成立或超时（refreshDialectStatusRow 是池线程重算 → EDT 收口）。 */
    private fun awaitUntil(timeoutMs: Long = 10_000, condition: () -> Boolean): Boolean {
        val deadline = System.currentTimeMillis() + timeoutMs
        while (System.currentTimeMillis() < deadline) {
            UIUtil.dispatchAllInvocationEvents()
            if (condition()) return true
            Thread.sleep(10)
        }
        UIUtil.dispatchAllInvocationEvents()
        return condition()
    }

    /** rerender 派发的 exec 预暖链收敛在本用例内（CrudSqlPreviewPanelRenderTest 同款防跨边界冲突）。 */
    private fun awaitExecPrewarmQuiescence() {
        val start = System.currentTimeMillis()
        while (System.currentTimeMillis() - start < 2_000 &&
            !DataSourceSelector.execPrewarmInFlightForTest()
        ) {
            UIUtil.dispatchAllInvocationEvents()
            Thread.sleep(10)
        }
        val deadline = System.currentTimeMillis() + 10_000
        while (System.currentTimeMillis() < deadline &&
            DataSourceSelector.execPrewarmInFlightForTest()
        ) {
            UIUtil.dispatchAllInvocationEvents()
            Thread.sleep(10)
        }
        UIUtil.dispatchAllInvocationEvents()
    }

    fun test换源到不同方言的源后预览按新源方言重渲染() {
        plantRegisteredSources()
        plantUrlProbe()
        DataSourceSelector.plantLastUsedMemoryForTest(project, "uuid-mysql", "mysql-src@local")
        val p = openInsertPreview()
        assertEquals(
            "前置：INSERT 预览应按 MySQL 渲染",
            "MySQL",
            p.currentForTest()?.effectiveDialect?.name,
        )

        // 生产写入入口切源（内部广播 LAST_USED_CHANGE_TOPIC；单测模式同步进刷新链）
        DataSourceSelector.rememberRunner(project, "pg-src@remote", "uuid-pg", null)

        val rerendered = awaitUntil {
            p.currentForTest()?.effectiveDialect?.name == "PostgreSQL"
        }
        try {
            assertEquals(
                "换源到 PG 源后存活面板必须按 PostgreSQL 重渲染（不许停留旧方言等闸门拦）",
                "PostgreSQL",
                p.currentForTest()?.effectiveDialect?.name,
            )
            assertEquals(
                "重渲染后决策应为绑定源强证据",
                cn.song.mybatisplus.visualizer.sql.DialectDecisionEngine.Source.BOUND_DATASOURCE,
                p.currentDialectDecision?.source,
            )
        } finally {
            if (rerendered) awaitExecPrewarmQuiescence()
        }
    }

    fun test用户编辑过文本时换源不重渲染() {
        plantRegisteredSources()
        plantUrlProbe()
        DataSourceSelector.plantLastUsedMemoryForTest(project, "uuid-mysql", "mysql-src@local")
        val p = openInsertPreview()
        val renderedBefore = p.lastRenderedSqlForTest()
        // 模拟用户编辑：改写编辑器文本（重渲染整篇重写，绝不能吞编辑——护栏本体）
        val editor = p.editorForTest()?.document
        WriteCommandAction.runWriteCommandAction(project) { editor?.setText("-- edited by user\n" + (renderedBefore ?: "")) }
        UIUtil.dispatchAllInvocationEvents()

        DataSourceSelector.rememberRunner(project, "pg-src@remote", "uuid-pg", null)

        // 决策刷新是异步池链——等它落地（决策被替换即链已跑完），再验文本未被重写
        val chainDone = awaitUntil {
            p.currentDialectDecision?.source ==
                cn.song.mybatisplus.visualizer.sql.DialectDecisionEngine.Source.BOUND_DATASOURCE
        }
        UIUtil.dispatchAllInvocationEvents()
        try {
            assertEquals(
                "文本被编辑过时不得重渲染（护栏：不能吞用户编辑）",
                "MySQL",
                p.currentForTest()?.effectiveDialect?.name,
            )
            assertEquals(
                "编辑器文本必须保持用户改写后的内容",
                "-- edited by user\n" + (renderedBefore ?: ""),
                p.editorForTest()?.document?.text,
            )
        } finally {
            if (chainDone) awaitExecPrewarmQuiescence()
        }
    }

    fun test换源到同方言的源不触发重渲染() {
        plantRegisteredSources()
        plantUrlProbe()
        DataSourceSelector.plantLastUsedMemoryForTest(project, "uuid-mysql", "mysql-src@local")
        val p = openInsertPreview()
        val textBefore = p.editorForTest()?.document?.text

        // 切到另一个 MySQL 源：方言一致，重渲染判据（方言不同）不命中
        DataSourceSelector.rememberRunner(project, "mysql-2nd@local", "uuid-mysql2", null)

        awaitUntil {
            p.currentDialectDecision?.source ==
                cn.song.mybatisplus.visualizer.sql.DialectDecisionEngine.Source.BOUND_DATASOURCE
        }
        UIUtil.dispatchAllInvocationEvents()
        assertEquals(
            "同方言换源不得无谓重渲染（文本应逐字不变）",
            textBefore,
            p.editorForTest()?.document?.text,
        )
        assertEquals(
            "方言保持 MySQL",
            "MySQL",
            p.currentForTest()?.effectiveDialect?.name,
        )
        awaitExecPrewarmQuiescence()
    }
}
