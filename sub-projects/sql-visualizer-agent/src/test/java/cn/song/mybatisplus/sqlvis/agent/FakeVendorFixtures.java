    /**
     * 包装器形态（T-OracleWrapperRegistry）：与 Oracle {@code OraclePreparedStatementWrapper} 同构——
     * 对外句柄是包装器自身，{@code execute*}/{@code setXxx} 全部转发给**包内物理语句**，物理语句挂在
     * 一个 Statement 类型字段上。用来钉住真实形态：prepare 面登记的是包装器，执行钩子却落在内层。
     */
